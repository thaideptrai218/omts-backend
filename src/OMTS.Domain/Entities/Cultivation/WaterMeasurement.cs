using OMTS.Domain.Common;
using OMTS.Domain.Constants;
using OMTS.Domain.Entities.Farming;
using OMTS.Domain.Entities.Platform;

namespace OMTS.Domain.Entities.Cultivation;

/// <summary>
/// One water measurement of a zone, made at a raft and confirmed by the person who recorded it against the meter photo
/// (WATER-01): no row exists before that confirmation and the values the OCR Service suggested are not kept
/// (BR-WATER-02). A correction changes this same row and a wrong measurement is voided, never deleted (BR-WATER-06).
/// </summary>
public class WaterMeasurement : AuditableEntity, IHasStatus
{
    public Guid ZoneId { get; set; }
    public FarmingZone Zone { get; set; } = null!;

    /// <summary>Where the water was measured; the measurement counts for the whole zone (BR-WATER-01).</summary>
    public Guid RaftId { get; set; }
    public Raft Raft { get; set; } = null!;

    public DateTimeOffset MeasuredAt { get; set; }

    public decimal Ph { get; set; }

    /// <summary>Salinity in ‰.</summary>
    public decimal Salinity { get; set; }

    /// <summary>Temperature in °C.</summary>
    public decimal Temperature { get; set; }

    /// <summary>Storage key of the meter photo, the proof of the values (BR-WATER-02); one measurement per photo.</summary>
    public string PhotoUrl { get; set; } = string.Empty;

    /// <summary>
    /// Idempotency key of the request: unique per (<see cref="MeasuredByAccountId"/>, ClientOperationId), so a re-sent
    /// request never creates a second record. Generated by the server when the client sends none.
    /// </summary>
    public Guid ClientOperationId { get; set; }

    public Guid? MeasuredByAccountId { get; set; }

    public bool ThresholdExceeded { get; set; }
    public string? ViolatedValues { get; set; }

    /// <summary>Copy of the zone thresholds when the measurement was saved; never changed afterwards (BR-WATER-04).</summary>
    public decimal? PhMinUsed { get; set; }
    public decimal? PhMaxUsed { get; set; }
    public decimal? SalinityMinUsed { get; set; }
    public decimal? SalinityMaxUsed { get; set; }
    public decimal? TemperatureMinUsed { get; set; }
    public decimal? TemperatureMaxUsed { get; set; }
    public DateTimeOffset? AlertedAt { get; set; }

    /// <summary>Why the record was voided (status Voided).</summary>
    public string? VoidReason { get; set; }

    public int StatusId { get; set; } = StatusIds.WaterMeasurement.Active;
    public Status Status { get; set; } = null!;
}
